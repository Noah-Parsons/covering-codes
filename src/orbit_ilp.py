"""Group-invariant covering codes by exact integer programming.

Fix a group G of isometries of the mixed space Z3^t x Z2^b and look only for codes that
are unions of G-orbits. A union of orbits covers the space iff it covers one
representative of every orbit, so the problem becomes a weighted set cover on the orbits:

    minimise   sum_j |O_j| x_j
    subject to sum_{j : O_j meets B(rep_i)} x_j >= 1   for every orbit i,   x binary.

With |G| large the orbit count is small and scipy's HiGHS (scipy.optimize.milp) solves it
exactly, which local search on raw words (src/search.py) cannot. With --ub the constraint
sum |O_j| x_j <= ub is added, so "infeasible" is a proof that no G-invariant code of that
size exists.

Group elements are monomial affine maps  w -> mult * w[perm] + shift  (coordinate
permutations inside the ternary and binary blocks, x -> 2x on ternary coordinates,
translations); these are all the isometries of the space.

Anything found is written to results/codes/ and only reported after src/checker.py
(independent code) validates the file.
"""
import argparse
import json
import os
import sys
import time

import numpy as np
from scipy.optimize import LinearConstraint, milp
from scipy.sparse import csr_matrix

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import checker  # noqa: E402  (independent verifier)
from search import all_digits, build_balls, radices, to_index, word_str  # noqa: E402


# ---------------------------------------------------------------- group
def gen_perm(digs, t, b, perm, mult, shift):
    """Permutation of word indices induced by w -> mult * w[perm] + shift."""
    r = radices(t, b)
    new = (digs[:, perm] * np.asarray(mult) + np.asarray(shift)) % r
    return to_index(new, t, b).astype(np.int32)


def closure(gens, cap):
    """All elements of the group generated by `gens` (None if order exceeds cap)."""
    N = len(gens[0])
    ident = np.arange(N, dtype=np.int32)
    seen = {ident.tobytes(): ident}
    frontier = [ident]
    while frontier:
        nxt = []
        for h in frontier:
            for g in gens:
                p = g[h]
                k = p.tobytes()
                if k not in seen:
                    seen[k] = p
                    nxt.append(p)
                    if len(seen) > cap:
                        return None
        frontier = nxt
    return list(seen.values())


def orbits(elems):
    """label[w] = smallest word in the orbit of w."""
    label = elems[0].copy()
    for p in elems[1:]:
        np.minimum(label, p, out=label)
    return label


def random_gen(rng, t, b, kind):
    """One random generator spec (perm, mult, shift) of the given kind."""
    n = t + b
    perm = list(range(n))
    mult = [1] * n
    shift = [0] * n
    if kind in ("perm", "mono", "affine"):
        for lo, hi in ((0, t), (t, n)):
            if hi - lo >= 2 and rng.random() < 0.8:
                k = int(rng.integers(2, hi - lo + 1))
                pos = lo + rng.choice(hi - lo, size=k, replace=False)
                cyc = np.roll(pos, 1)
                for a, c in zip(pos, cyc):
                    perm[a] = int(c)
    if kind in ("mono", "affine", "neg"):
        for i in range(t):
            if rng.random() < (1.0 if kind == "neg" else 0.5):
                mult[i] = 2
    if kind in ("trans", "affine"):
        w = int(rng.integers(1, n + 1))
        for i in rng.choice(n, size=w, replace=False):
            shift[i] = int(rng.integers(1, 3 if i < t else 2))
    return perm, mult, shift


# ---------------------------------------------------------------- set cover
def orbit_problem(balls, label):
    reps, inv, sizes = np.unique(label, return_inverse=True, return_counts=True)
    rows, cols = [], []
    for i, w in enumerate(reps):
        c = np.unique(inv[balls[w]])
        rows.append(np.full(len(c), i))
        cols.append(c)
    rows = np.concatenate(rows)
    cols = np.concatenate(cols)
    A = csr_matrix((np.ones(len(rows)), (rows, cols)), shape=(len(reps), len(reps)))
    return reps, inv, sizes, A


def solve(A, sizes, ub, tlim):
    """Returns (status, x). status: 'optimal', 'feasible', 'infeasible', 'timeout'."""
    cons = [LinearConstraint(A, 1, np.inf)]
    if ub is not None:
        cons.append(LinearConstraint(sizes.reshape(1, -1).astype(float), -np.inf, ub))
    res = milp(c=sizes.astype(float), constraints=cons, integrality=np.ones(len(sizes)),
               bounds=(0, 1), options={"time_limit": tlim, "disp": False})
    if res.status == 2:
        return "infeasible", None
    if res.x is None:
        return "timeout", None
    return ("optimal" if res.status == 0 else "feasible"), np.round(res.x).astype(int)


def solve_min(A, sizes, ub, tlim):
    """Minimise the code size with no cap and read off HiGHS's proven lower bound. Sizes are
    integers, so a dual bound above ub means no invariant code of size <= ub exists. In
    practice this closes far faster than the capped feasibility problem in solve()."""
    res = milp(c=sizes.astype(float), constraints=[LinearConstraint(A, 1, np.inf)],
               integrality=np.ones(len(sizes)), bounds=(0, 1),
               options={"time_limit": tlim, "disp": False})
    bound = getattr(res, "mip_dual_bound", None)
    x = None if res.x is None else np.round(res.x).astype(int)
    if x is not None and int(sizes @ x) <= ub:
        return "feasible", x, bound
    if bound is not None and np.ceil(bound - 1e-6) > ub:
        return "infeasible", None, bound
    return "timeout", None, bound


def solve_cpsat(A, sizes, ub, tlim, workers=4):
    """Same question as solve() with a size cap, answered by OR-tools CP-SAT (integer
    arithmetic throughout, so an independent check on the HiGHS verdicts)."""
    from ortools.sat.python import cp_model
    m = cp_model.CpModel()
    x = [m.NewBoolVar(f"x{j}") for j in range(len(sizes))]
    A = A.tocsr()
    for i in range(A.shape[0]):
        m.AddBoolOr([x[j] for j in A.indices[A.indptr[i]:A.indptr[i + 1]]])
    m.Add(sum(int(s) * v for s, v in zip(sizes, x)) <= int(ub))
    sol = cp_model.CpSolver()
    sol.parameters.max_time_in_seconds = float(tlim)
    sol.parameters.num_workers = workers
    st = sol.Solve(m)
    if st == cp_model.INFEASIBLE:
        return "infeasible", None
    if st in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        return "feasible", np.array([sol.Value(v) for v in x])
    return "timeout", None


def verify_and_save(words, t, b, R, note):
    strs = [word_str(int(x), t, b) for x in sorted(words)]
    ok, m, nbad = checker.check(checker.parse_code(strs, t, b), t, b, R)
    path = ""
    if ok:
        path = os.path.join(ROOT, "results", "codes", f"K_{t}_{b}_{R}_M{m}_orbit.txt")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(f"# K(t={t}, b={b}, R={R}) covering, M={m} {note}\n")
            f.write("\n".join(strs) + "\n")
    return ok, m, nbad, path


# ---------------------------------------------------------------- driver
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("t", type=int)
    ap.add_argument("b", type=int)
    ap.add_argument("R", type=int)
    ap.add_argument("--record", type=int, required=True, help="published upper bound")
    ap.add_argument("--groups", type=int, default=50, help="number of random groups to try")
    ap.add_argument("--kinds", default="trans,perm,mono,affine,neg")
    ap.add_argument("--ngen", default="1,2,3", help="allowed numbers of generators")
    ap.add_argument("--min-order", type=int, default=2)
    ap.add_argument("--max-order", type=int, default=400)
    ap.add_argument("--max-orbits", type=int, default=700)
    ap.add_argument("--min-orbits", type=int, default=0)
    ap.add_argument("--ub", type=int, help="size cap (default record-1; 0 = no cap, pure minimise)")
    ap.add_argument("--tlim", type=float, default=20.0, help="solver seconds per group")
    ap.add_argument("--time", type=float, default=170.0, help="total wall seconds")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--label", default="")
    ap.add_argument("--replay", help="rerun the groups logged as 'timeout' under this label (same target)")
    a = ap.parse_args()

    t, b, R = a.t, a.b, a.R
    ub = a.record - 1 if a.ub is None else (a.ub or None)
    rng = np.random.default_rng(a.seed)
    digs = all_digits(t, b)
    balls = build_balls(t, b, R)
    kinds = a.kinds.split(",")
    ngens = [int(x) for x in a.ngen.split(",")]
    log_path = os.path.join(ROOT, "results", "orbit_runs.jsonl")
    name = f"K({t},{b},{R})"
    print(f"{name}: N={len(digs)} |B|={balls.shape[1]} record={a.record} ub={ub} seed={a.seed}", flush=True)

    replay = []
    if a.replay:
        with open(log_path) as f:
            rows = [json.loads(ln) for ln in f]
        replay = [r["gens"] for r in rows
                  if r["target"] == name and r["label"] == a.replay and r["status"] == "timeout"]
        replay.sort(key=lambda g: json.dumps(g))
        print(f"replaying {len(replay)} undecided groups from label {a.replay!r}", flush=True)

    t0 = time.time()
    seen_sig = set()
    tried = 0
    counts = {"optimal": 0, "feasible": 0, "infeasible": 0, "timeout": 0}
    best = None
    attempts = 0
    while tried < a.groups and time.time() - t0 < a.time and attempts < 200 * a.groups:
        attempts += 1
        if a.replay:
            if not replay:
                break
            specs = replay.pop()
        else:
            specs = [random_gen(rng, t, b, str(rng.choice(kinds))) for _ in range(int(rng.choice(ngens)))]
        elems = closure([gen_perm(digs, t, b, *s) for s in specs], a.max_order)
        if elems is None or len(elems) < a.min_order:
            continue
        label = orbits(elems)
        reps, inv, sizes, A = orbit_problem(balls, label)
        if not (a.min_orbits <= len(reps) <= a.max_orbits):
            continue
        sig = (len(elems), tuple(np.bincount(sizes).tolist()), A.nnz)
        if sig in seen_sig:
            continue
        seen_sig.add(sig)
        tried += 1
        ts = time.time()
        status, x = solve(A, sizes, ub, a.tlim)
        counts[status] += 1
        M = int(sizes @ x) if x is not None else None
        row = {"target": name, "label": a.label, "seed": a.seed, "gens": specs, "order": len(elems),
               "orbits": len(reps), "ub": ub, "status": status, "M": M,
               "solve_s": round(time.time() - ts, 2)}
        if x is not None:
            words = np.flatnonzero(x[inv] == 1)
            if best is None or M < best:
                best = M
            if M < a.record:
                ok, m, nbad, path = verify_and_save(words, t, b, R, f"G-invariant, gens={json.dumps(specs)}")
                row["checker"] = "VALID" if ok else f"INVALID({nbad})"
                row["file"] = os.path.relpath(path, ROOT) if path else ""
                print(f"  *** M={m} < record {a.record}: checker {row['checker']} {row['file']}", flush=True)
        with open(log_path, "a") as f:
            f.write(json.dumps(row) + "\n")
        print(f"  |G|={len(elems):4d} orbits={len(reps):4d} {status:10s} M={M} "
              f"({row['solve_s']}s)", flush=True)
    print(f"done: {tried} groups in {time.time() - t0:.0f}s, {counts}, best M={best}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
