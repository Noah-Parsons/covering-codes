"""Build the per-class evidence table for the K(1,7,1) note from the result logs.

Reads results/classify.jsonl (first pass) and results/recheck.jsonl (second solver) and writes
paper/table_1_7_1.tex. Every number in the table comes from those two files.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET, UB = "K(1,7,1)", 47


def describe(name):
    """p2:t0c1s,b2c3f -> (p, ternary symbol map, binary p-cycles, flipped fixed coordinates)."""
    p, a, c, bc, bk = map(int, re.fullmatch(r"p(\d+):t(\d+)c(\d+)s,b(\d+)c(\d+)f", name).groups())
    assert a == 0
    tern = "id"
    if c:
        tern = r"$(1\,2)$" if p == 2 else r"$x\mapsto x+1$"
    return p, tern, bc, bk


def main():
    first = {}
    for ln in open(os.path.join(ROOT, "results", "classify.jsonl")):
        r = json.loads(ln)
        if r["target"] == TARGET and r["ub"] == UB and r["status"] == "infeasible":
            first[r["class"]] = r
    scip = {}
    for ln in open(os.path.join(ROOT, "results", "recheck.jsonl")):
        r = json.loads(ln)
        if r["target"] == TARGET and r["ub"] == UB and r["solver"] == "scip" and r["status"] == "infeasible":
            scip[r["class"]] = r
    assert len(first) == 46 and set(scip) == set(first), (len(first), len(scip))
    # recheck.solve_scip returns an int only when SCIP proved optimality (a bound is a float)
    assert all(isinstance(r["info"], int) for r in scip.values())

    rows = sorted(first, key=lambda c: (-describe(c)[0], describe(c)[1], describe(c)[2], describe(c)[3]))
    out = []
    for i, c in enumerate(rows, 1):
        p, tern, bc, bk = describe(c)
        f, s = first[c], scip[c]
        hb = f.get("dual_bound")
        hb = "--" if hb is None else f"{hb:.2f}"
        out.append(f"{i} & {p} & {tern} & {bc} & {bk} & {f['orbits']} & {hb} & {f['solve_s']:.1f} & "
                   f"{s['info']} & {s['solve_s']:.1f} \\\\")
    with open(os.path.join(ROOT, "paper", "table_1_7_1.tex"), "w") as fh:
        fh.write("% generated by paper/make_table.py -- do not edit by hand\n")
        # The closing rule lives here: \input followed by \bottomrule breaks longtable.
        fh.write("\n".join(out) + "\n\\bottomrule\n")
    print(f"wrote {len(out)} rows")


if __name__ == "__main__":
    main()
